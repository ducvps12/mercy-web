const fs = require('fs');
const path = require('path');

try {
  const srcDir = 'C:\\Users\\mtien\\OneDrive\\Desktop\\web-mercy\\Product-20260407T075101Z-3-001\\Product';
  const dstDir = path.join(__dirname, 'public', 'products');

  if (!fs.existsSync(dstDir)) {
    fs.mkdirSync(dstDir, { recursive: true });
  }

  const folders = fs.readdirSync(srcDir, { withFileTypes: true }).filter(d => d.isDirectory());

  const products = [];
  let idCounter = 100;

  for (const folder of folders) {
    const sku = folder.name;
    const skuDir = path.join(srcDir, sku);
    
    // ignore cover folders
    if (sku.includes("Ảnh bìa") || sku.includes("Hình EC")) continue;

    const files = fs.readdirSync(skuDir).filter(f => f.endsWith('.png') || f.endsWith('.jpg') || f.endsWith('.jpeg'));
    const images = [];

    for (let i = 0; i < Math.min(4, files.length); i++) {
      const file = files[i];
      const srcPath = path.join(skuDir, file);
      const destName = sku.replace(/\s+/g, '-') + '-' + i + '.jpg';
      const dstPath = path.join(dstDir, destName);
      
      // Copy file
      fs.copyFileSync(srcPath, dstPath);
      images.push('/products/' + destName);
    }

    if (images.length === 0) continue;

    let price = 4990000;
    if (sku.includes('5.1') || sku.includes('6.0')) price = 5990000;
    if (sku.includes('RBnu')) price = 5490000;
    if (sku.includes('Bao da') || sku.includes('Bìa Tết')) price = 199000;

    let name = "Kính Thông Minh Mercy " + sku;
    let category = "Kính Mắt Thông Minh";
    if (sku.includes('RBnu')) {
       name = "Robot AI Mercy " + sku.replace('RBnu-', '');
       category = "Balo Thông Minh"; // Map appropriately for now to existing categories
    }
    if (sku.includes('Bao da') || sku.includes('Bìa Tết')) {
       name = "Phụ kiện " + sku;
       category = "Phụ Kiện";
    }

    products.push({
      id: idCounter++,
      name: name,
      price: price,
      originalPrice: price + 1000000,
      image: images[0],
      images: images,
      description: "Sản phẩm " + name + " cao cấp từ thương hiệu Mercy. Thiết kế hiện đại, thông minh, mang lại trải nghiệm tuyệt vời.",
      specs: [
        { label: "Mã SKU", value: sku },
        { label: "Thương hiệu", value: "Mercy" },
        { label: "Bảo hành", value: "12 tháng" }
      ],
      category: category,
    });
  }

  const tsContent = "// Auto generated by AI import script\n" +
"export interface ProductData {\n" +
"  id: number;\n" +
"  name: string;\n" +
"  price: number;\n" +
"  originalPrice?: number;\n" +
"  image: string;\n" +
"  images: string[];\n" +
"  description: string;\n" +
"  specs: { label: string; value: string }[];\n" +
"  category: string;\n" +
"}\n\n" +
"export const formatPrice = (price: number) =>\n" +
"  new Intl.NumberFormat(\"vi-VN\").format(price) + \"đ\";\n\n" +
"export const products: ProductData[] = " + JSON.stringify(products, null, 2) + ";\n";

  fs.writeFileSync(path.join(__dirname, 'src', 'data', 'products.ts'), tsContent);
  console.log("Success! Imported " + products.length + " products into src/data/products.ts!");
} catch (e) {
  console.error(e);
}
